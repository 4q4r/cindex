import { useState, useCallback, useMemo, useEffect, useRef } from 'react';
import { ChevronLeft, ChevronRight, Check } from 'lucide-react';
import { Header } from './components/Header';
import { SearchBar } from './components/SearchBar';
import { FilterPanel } from './components/FilterPanel';
import { InfoBar } from './components/InfoBar';
import { ResultCard } from './components/ResultCard';
import { EmptyState } from './components/EmptyState';
import { LoadingState } from './components/LoadingState';
import { searchArticles } from './api/search';
import { Filters, SearchResult, SearchState, ViewMode, DEFAULT_FILTERS, ALL_SOURCES } from './types';

const PER_PAGE = 5;

export default function App() {
  const [searchState, setSearchState] = useState<SearchState>('idle');
  const [query, setQuery] = useState('');
  const [expression, setExpression] = useState('');
  const [lastQuery, setLastQuery] = useState('');
  const [filters, setFilters] = useState<Filters>({ ...DEFAULT_FILTERS });
  const [rawResults, setRawResults] = useState<SearchResult[]>([]);
  const [totalBeforeFilter, setTotalBeforeFilter] = useState(0);
  const [filteredOutCount, setFilteredOutCount] = useState(0);
  const [sourcesQueried, setSourcesQueried] = useState(ALL_SOURCES.length);
  const [sourcesFailed, setSourcesFailed] = useState<string[]>([]);
  const [lastSearchTime, setLastSearchTime] = useState<Date | null>(null);
  const [viewMode, setViewMode] = useState<ViewMode>('comfortable');
  const [mobileFiltersOpen, setMobileFiltersOpen] = useState(false);
  const [currentPage, setCurrentPage] = useState(1);
  const [copyNotification, setCopyNotification] = useState<string | null>(null);
  const notifTimeoutRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  const filteredResults = useMemo(() => {
    let results = [...rawResults];

    if (filters.sources.length < ALL_SOURCES.length) {
      const sourceSet = new Set(filters.sources);
      results = results.filter((r) => sourceSet.has(r.source));
    }

    if (filters.doiOnly) results = results.filter((r) => r.eligibilityEvidence.doiAndJournalCard);
    if (filters.peerReviewedOnly) results = results.filter((r) => r.eligibilityEvidence.peerReviewed);
    if (filters.indexedOnly) results = results.filter((r) => r.eligibilityEvidence.indexed);
    if (filters.excludePreprints) results = results.filter((r) => r.eligibilityEvidence.notPreprint);

    if (filters.dateFrom) {
      const from = parseInt(filters.dateFrom, 10);
      if (!Number.isNaN(from)) results = results.filter((r) => (r.year ?? 0) >= from);
    }
    if (filters.dateTo) {
      const to = parseInt(filters.dateTo, 10);
      if (!Number.isNaN(to)) results = results.filter((r) => (r.year ?? 3000) <= to);
    }

    switch (filters.sortBy) {
      case 'newest':
        results.sort((a, b) => (b.year ?? 0) - (a.year ?? 0));
        break;
      case 'metadata':
        results.sort((a, b) => {
          const scoreA = Object.keys(a.identifiers || {}).length + Math.round(a.eligibilityConfidence.overall / 25);
          const scoreB = Object.keys(b.identifiers || {}).length + Math.round(b.eligibilityConfidence.overall / 25);
          return scoreB - scoreA;
        });
        break;
      case 'relevance':
      default:
        results.sort((a, b) => b.eligibilityConfidence.overall - a.eligibilityConfidence.overall);
        break;
    }

    return results;
  }, [rawResults, filters]);

  useEffect(() => {
    setFilteredOutCount(totalBeforeFilter - filteredResults.length);
  }, [filteredResults.length, totalBeforeFilter]);

  const totalPages = Math.ceil(filteredResults.length / PER_PAGE);
  const paginatedResults = useMemo(() => {
    const start = (currentPage - 1) * PER_PAGE;
    return filteredResults.slice(start, start + PER_PAGE);
  }, [filteredResults, currentPage]);

  useEffect(() => {
    setCurrentPage(1);
  }, [rawResults]);

  const hasActiveFilters = useMemo(() => {
    return (
      filters.sources.length < ALL_SOURCES.length ||
      filters.doiOnly ||
      filters.peerReviewedOnly ||
      filters.indexedOnly ||
      filters.excludePreprints ||
      filters.dateFrom !== '' ||
      filters.dateTo !== '' ||
      filters.sortBy !== 'relevance'
    );
  }, [filters]);

  const handleSearch = useCallback(
    async (searchQuery?: string) => {
      const q = searchQuery || query;
      if (!q.trim()) return;

      setLastQuery(q);
      setSearchState('loading');
      setCurrentPage(1);

      try {
        const style = filters.citationStyle === 'gost2003' ? 'gost_2003' : 'gost_2018';
        const results = await searchArticles({
          query: q,
          expression: expression.trim() || undefined,
          style,
          force_refresh: false,
        });

        setRawResults(results);
        setTotalBeforeFilter(results.length);
        setSourcesQueried(ALL_SOURCES.length);
        setSourcesFailed([]);
        setLastSearchTime(new Date());

        if (results.length === 0) {
          setSearchState('empty');
        } else {
          setSearchState('results');
        }
      } catch {
        setRawResults([]);
        setTotalBeforeFilter(0);
        setSearchState('error');
      }
    },
    [query, expression, filters.citationStyle],
  );

  const handleCopy = useCallback(async (text: string, type: string) => {
    try {
      await navigator.clipboard.writeText(text);
      setCopyNotification(type === 'citation' ? 'Цитирование скопировано' : 'Фрагмент скопирован');
      if (notifTimeoutRef.current) clearTimeout(notifTimeoutRef.current);
      notifTimeoutRef.current = setTimeout(() => setCopyNotification(null), 2000);
    } catch {
      const textarea = document.createElement('textarea');
      textarea.value = text;
      document.body.appendChild(textarea);
      textarea.select();
      document.execCommand('copy');
      document.body.removeChild(textarea);
      setCopyNotification(type === 'citation' ? 'Цитирование скопировано' : 'Фрагмент скопирован');
      if (notifTimeoutRef.current) clearTimeout(notifTimeoutRef.current);
      notifTimeoutRef.current = setTimeout(() => setCopyNotification(null), 2000);
    }
  }, []);

  const handleClearFilters = useCallback(() => {
    setFilters({ ...DEFAULT_FILTERS });
  }, []);

  const handleExampleClick = useCallback(
    (q: string) => {
      setQuery(q);
      setExpression('');
      setTimeout(() => handleSearch(q), 0);
    },
    [handleSearch],
  );

  const showResults = searchState === 'results' || (searchState === 'partial' && filteredResults.length > 0);

  return (
    <div className="min-h-screen bg-bg-primary">
      <Header
        resultCount={filteredResults.length}
        lastSearchTime={lastSearchTime}
        sourcesQueried={sourcesQueried}
        sourcesFailed={sourcesFailed}
        searchState={searchState}
      />

      <div className="max-w-[1440px] mx-auto px-6 py-6">
        <div className="flex gap-8">
          <FilterPanel
            filters={filters}
            onFiltersChange={setFilters}
            isMobileOpen={mobileFiltersOpen}
            onMobileClose={() => setMobileFiltersOpen(false)}
          />

          <div className="flex-1 min-w-0 h-[calc(100vh-92px)] overflow-y-auto pr-1">
            <SearchBar
              query={query}
              expression={expression}
              onQueryChange={setQuery}
              onExpressionChange={setExpression}
              onSearch={() => handleSearch()}
              isLoading={searchState === 'loading'}
            />

            <div className="py-5">
              {showResults && (
                <div className="mb-5">
                  <InfoBar
                    totalResults={filteredResults.length}
                    filteredOut={filteredOutCount}
                    sourcesFailed={sourcesFailed}
                    onClearFilters={handleClearFilters}
                    onToggleMobileFilters={() => setMobileFiltersOpen(true)}
                    viewMode={viewMode}
                    onViewModeChange={setViewMode}
                    hasActiveFilters={hasActiveFilters}
                  />
                </div>
              )}

              {searchState === 'partial' && filteredResults.length > 0 && (
                <div className="mb-5 flex items-center gap-2 bg-warning-muted/20 border border-warning/20 rounded-lg px-4 py-2.5 text-xs text-warning">
                  <span>Частичный результат: часть источников недоступна ({sourcesFailed.join(', ')}).</span>
                </div>
              )}

              {searchState === 'loading' && <LoadingState sourcesQueried={sourcesQueried} />}

              {showResults && (
                <div className="space-y-5">
                  {paginatedResults.map((result, index) => (
                    <div key={result.id} style={{ animationDelay: `${index * 60}ms` }}>
                      <ResultCard result={result} query={lastQuery} viewMode={viewMode} onCopy={handleCopy} />
                    </div>
                  ))}

                  {totalPages > 1 && (
                    <div className="flex items-center justify-center gap-2 pt-6 pb-2">
                      <button
                        onClick={() => setCurrentPage((p) => Math.max(1, p - 1))}
                        disabled={currentPage === 1}
                        className="flex items-center gap-1 px-3 py-2 text-xs text-text-secondary hover:text-text-primary bg-bg-elevated border border-border-default rounded-lg disabled:opacity-30 disabled:cursor-not-allowed transition-colors"
                      >
                        <ChevronLeft className="w-4 h-4" />
                        Назад
                      </button>
                      <div className="flex items-center gap-1">
                        {Array.from({ length: totalPages }, (_, i) => i + 1)
                          .filter((page) => {
                            if (page === 1 || page === totalPages) return true;
                            if (Math.abs(page - currentPage) <= 1) return true;
                            return false;
                          })
                          .map((page, idx, arr) => {
                            const prevPage = arr[idx - 1];
                            const showEllipsis = prevPage && page - prevPage > 1;
                            return (
                              <span key={page} className="flex items-center">
                                {showEllipsis && <span className="px-2 text-text-tertiary text-xs">...</span>}
                                <button
                                  onClick={() => setCurrentPage(page)}
                                  className={`w-9 h-9 rounded-lg text-xs font-medium transition-colors ${
                                    page === currentPage
                                      ? 'bg-accent text-white'
                                      : 'text-text-secondary hover:bg-bg-hover hover:text-text-primary'
                                  }`}
                                >
                                  {page}
                                </button>
                              </span>
                            );
                          })}
                      </div>
                      <button
                        onClick={() => setCurrentPage((p) => Math.min(totalPages, p + 1))}
                        disabled={currentPage === totalPages}
                        className="flex items-center gap-1 px-3 py-2 text-xs text-text-secondary hover:text-text-primary bg-bg-elevated border border-border-default rounded-lg disabled:opacity-30 disabled:cursor-not-allowed transition-colors"
                      >
                        Далее
                        <ChevronRight className="w-4 h-4" />
                      </button>
                    </div>
                  )}
                </div>
              )}

              {(searchState === 'idle' ||
                searchState === 'empty' ||
                searchState === 'error' ||
                (searchState === 'partial' && filteredResults.length === 0)) && (
                <EmptyState
                  state={searchState}
                  onRetry={() => handleSearch()}
                  onExampleClick={handleExampleClick}
                  sourcesFailed={sourcesFailed}
                />
              )}
            </div>
          </div>
        </div>
      </div>

      {copyNotification && (
        <div className="fixed bottom-6 right-6 z-50 flex items-center gap-2 bg-bg-card border border-success/30 text-success px-4 py-2.5 rounded-lg shadow-xl animate-fade-in">
          <Check className="w-4 h-4" />
          <span className="text-sm">{copyNotification}</span>
        </div>
      )}
    </div>
  );
}
