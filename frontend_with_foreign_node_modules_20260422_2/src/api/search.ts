import { ApiSearchResponse, SearchResult } from '../types';

const API_PREFIX = '/api/v1';

export interface SearchApiRequest {
  query: string;
  expression?: string;
  style: 'gost_2018' | 'gost_2003';
  force_refresh?: boolean;
}

function normalizeConfidence(value: number): number {
  if (Number.isNaN(value)) return 0;
  if (value <= 1) return Math.round(value * 100);
  if (value > 100) return 100;
  return Math.round(value);
}

export function mapApiResult(item: ApiSearchResponse['results'][number]): SearchResult {
  return {
    id: String(item.id),
    title: item.title,
    citationFull: item.citation_full,
    snippet: item.snippet,
    year: item.year,
    source: item.source,
    identifiers: item.identifiers ?? {},
    eligibilityEvidence: {
      peerReviewed: Boolean(item.eligibility_evidence.peer_reviewed),
      indexed: Boolean(item.eligibility_evidence.indexed),
      doiAndJournalCard: Boolean(item.eligibility_evidence.doi_and_journal_card),
      notPreprint: Boolean(item.eligibility_evidence.not_preprint),
    },
    eligibilityConfidence: {
      peerReviewed: normalizeConfidence(item.eligibility_confidence.peer_reviewed),
      indexed: normalizeConfidence(item.eligibility_confidence.indexed),
      doiAndJournalCard: normalizeConfidence(item.eligibility_confidence.doi_and_journal_card),
      notPreprint: normalizeConfidence(item.eligibility_confidence.not_preprint),
      overall: normalizeConfidence(item.eligibility_confidence.overall),
    },
    url: item.url,
  };
}

export async function searchArticles(payload: SearchApiRequest): Promise<SearchResult[]> {
  const response = await fetch(`${API_PREFIX}/search`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(payload),
  });

  if (!response.ok) {
    throw new Error(`Search API failed: ${response.status}`);
  }

  const data = (await response.json()) as ApiSearchResponse;
  return data.results.map(mapApiResult);
}
