export function simulateSearch(query: string): Promise<{
  results: SearchResult[];
  totalBeforeFilter: number;
  filteredOut: number;
  sourcesQueried: number;
  sourcesFailed: string[];
}> {
  return new Promise((resolve) => {
    const delay = 1200 + Math.random() * 1800;
    
    setTimeout(() => {
      const q = query.toLowerCase();
      
      // Score and filter results based on query relevance
      const scored = mockResults.map(r => {
        const titleMatch = r.title.toLowerCase().includes(q) || 
          (r.titleRu && r.titleRu.toLowerCase().includes(q));
        const snippetMatch = r.snippet.toLowerCase().includes(q);
        const authorMatch = r.authors.some(a => a.toLowerCase().includes(q));
        const journalMatch = r.journal.toLowerCase().includes(q);
        
        let score = r.relevanceScore;
        if (titleMatch) score = Math.min(100, score + 30);
        if (snippetMatch) score = Math.min(100, score + 15);
        if (authorMatch) score = Math.min(100, score + 10);
        if (journalMatch) score = Math.min(100, score + 5);
        
        // Also check individual words
        const words = q.split(/\s+/).filter(w => w.length > 2);
        let wordScore = 0;
        for (const word of words) {
          if (r.title.toLowerCase().includes(word)) wordScore += 5;
          if (r.snippet.toLowerCase().includes(word)) wordScore += 3;
          if (r.journal.toLowerCase().includes(word)) wordScore += 2;
          for (const a of r.authors) {
            if (a.toLowerCase().includes(word)) wordScore += 2;
          }
        }
        score = Math.min(100, score + wordScore);
        
        return { ...r, relevanceScore: score };
      });
      
      // Return results with some relevance
      let results = scored.filter(r => r.relevanceScore > 30);
      
      // If query is empty or generic, return all with base scores
      if (q.trim() === '' || q.length < 3) {
        results = mockResults.map(r => ({ ...r }));
      }
      
      // Sort by relevance
      results.sort((a, b) => b.relevanceScore - a.relevanceScore);
      
      // Simulate some sources failing occasionally
      const sourcesFailed: string[] = [];
      if (Math.random() > 0.7) {
        const possibleFailures = ['Scopus', 'Web of Science', 'IEEE Xplore', 'JSTOR'];
        const failCount = Math.floor(Math.random() * 2) + 1;
        for (let i = 0; i < failCount; i++) {
          sourcesFailed.push(possibleFailures[Math.floor(Math.random() * possibleFailures.length)]);
        }
      }
      
      const totalBeforeFilter = results.length + Math.floor(Math.random() * 5);
      const filteredOut = Math.floor(Math.random() * 3);
      
      resolve({
        results,
        totalBeforeFilter,
        filteredOut,
        sourcesQueried: 23,
        sourcesFailed,
      });
    }, delay);
  });
}
