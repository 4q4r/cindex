export interface ApiSearchResponse {
  query: string;
  count: number;
  results: ApiSearchResult[];
}

export interface ApiSearchResult {
  id: number;
  title: string;
  citation_full: string;
  snippet: string;
  year: number | null;
  source: string;
  identifiers?: Record<string, string>;
  eligibility_evidence: {
    peer_reviewed: boolean;
    indexed: boolean;
    doi_and_journal_card: boolean;
    not_preprint: boolean;
  };
  eligibility_confidence: {
    peer_reviewed: number;
    indexed: number;
    doi_and_journal_card: number;
    not_preprint: number;
    overall: number;
  };
  url: string;
}

export interface SearchResult {
  id: string;
  title: string;
  citationFull: string;
  snippet: string;
  year: number | null;
  source: string;
  identifiers: Record<string, string>;
  eligibilityEvidence: {
    peerReviewed: boolean;
    indexed: boolean;
    doiAndJournalCard: boolean;
    notPreprint: boolean;
  };
  eligibilityConfidence: {
    peerReviewed: number;
    indexed: number;
    doiAndJournalCard: number;
    notPreprint: number;
    overall: number;
  };
  url: string;
}

export interface Filters {
  citationStyle: 'gost2018' | 'gost2003';
  sources: string[];
  doiOnly: boolean;
  peerReviewedOnly: boolean;
  indexedOnly: boolean;
  excludePreprints: boolean;
  dateFrom: string;
  dateTo: string;
  sortBy: 'relevance' | 'newest' | 'metadata';
}

